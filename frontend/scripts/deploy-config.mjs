// Netlify build step (see netlify.toml). Reads API_BASE_URL, the URL of the MyBus API (e.g. https://mybus-api.onrender.com).
//   node scripts/deploy-config.mjs --check   before "ng build": stop early when API_BASE_URL is missing or invalid
//   node scripts/deploy-config.mjs           after "ng build": write into the build output (never into the source tree)
//     - config.js   the runtime settings with the API URL (the app calls the API directly, cross-origin)
//     - _redirects  share links and community photos proxied to the API, then the single-page-app fallback
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../dist/frontend/browser');
const fail = (message) => {
  console.error(`[deploy-config] ${message}`);
  process.exit(1);
};

const raw = (process.env.API_BASE_URL ?? '').trim();
if (!raw) fail('API_BASE_URL is not set. In Netlify open Site configuration > Environment variables and set it to the API URL, e.g. https://mybus-api.onrender.com');
let url;
try {
  url = new URL(raw);
} catch {
  fail('API_BASE_URL must be a full URL, e.g. https://mybus-api.onrender.com');
}
if (url.pathname.replace(/\/+$/, '') !== '' || url.search || url.hash) fail('API_BASE_URL must be the API origin only (https://host), without a path such as /api');
const local = ['localhost', '127.0.0.1'].includes(url.hostname);
if (url.protocol !== 'https:' && !(local && url.protocol === 'http:')) fail('API_BASE_URL must use https:// (plain http is only accepted for localhost)');
const api = url.origin;

if (process.argv.includes('--check')) {
  console.log(`[deploy-config] API_BASE_URL is set (${api})`);
  process.exit(0);
}
if (!fs.existsSync(path.join(OUT, 'index.html'))) fail(`no build output in ${OUT}: run "npm run build" first`);

fs.writeFileSync(
  path.join(OUT, 'config.js'),
  `// Generated by scripts/deploy-config.mjs at build time.\nwindow.MYBUS_CONFIG = ${JSON.stringify({ apiBaseUrl: api })};\n`,
);
fs.writeFileSync(
  path.join(OUT, '_redirects'),
  [
    '# Generated by scripts/deploy-config.mjs at build time (the only redirect rules of the site).',
    '# Share links and community photos stay on this domain and are fetched from the API.',
    `/share/*    ${api}/share/:splat    200`,
    `/uploads/*  ${api}/uploads/:splat  200`,
    '# Every other path is an app route.',
    '/*          /index.html  200',
    '',
  ].join('\n'),
);
console.log(`[deploy-config] wrote config.js and _redirects for ${api}`);
